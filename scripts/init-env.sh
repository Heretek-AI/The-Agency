#!/usr/bin/env bash
# init-env for The Agency (Stage 1b, Step 7).
# From the salvaged studio init: creates .env (host uid/gid, gateway port,
# a random value for every PW_<NAME>, PROXY_PW_<NAME>, and token) and a
# placeholder .env.provider, both mode 0600, never overwriting an existing
# file. Never prints a secret: values are generated silently.
set -u

ROOT="$(git rev-parse --show-toplevel)"
ENVFILE="$ROOT/.env"
PROVIDERFILE="$ROOT/.env.provider"

if [ -f "$ENVFILE" ]; then
  echo "init-env: $ENVFILE exists; refusing to overwrite (delete it to re-init)" >&2
  exit 1
fi
if [ -f "$PROVIDERFILE" ]; then
  echo "init-env: $PROVIDERFILE exists; refusing to overwrite (delete it to re-init)" >&2
  exit 1
fi

command -v python3 >/dev/null 2>&1 || {
  echo "init-env: missing required command python3" >&2
  exit 1
}

gen_secret() {
  python3 -c "import secrets; print(secrets.token_urlsafe(24))" || {
    echo "init-env: secret generation failed" >&2
    exit 1
  }
}

OPENCODE_VERSION="$(grep '^OPENCODE_VERSION=' "$ROOT/versions.env" | cut -d= -f2)"
BUN_VERSION="$(grep '^BUN_VERSION=' "$ROOT/versions.env" | cut -d= -f2)"
if [ -z "$OPENCODE_VERSION" ] || [ -z "$BUN_VERSION" ]; then
  echo "init-env: versions.env lacks OPENCODE_VERSION or BUN_VERSION" >&2
  exit 1
fi

{
  echo "# Generated by scripts/init-env.sh. Do not commit."
  echo "COMPOSE_PROJECT_NAME=agency"
  echo "AGENCY_MODEL="
  echo "AGENT_UID=$(id -u)"
  echo "AGENT_GID=$(id -g)"
  echo "AGENCY_HTTP_PORT=8081"
  echo "OPENCODE_VERSION=$OPENCODE_VERSION"
  echo "BUN_VERSION=$BUN_VERSION"
  for expert in director scout architect product frontend backend dba platform security qa reviewer docs; do
    upper=$(printf '%s' "$expert" | tr 'a-z-' 'A-Z_')
    echo "PW_$upper=$(gen_secret)"
    echo "PROXY_PW_$upper=$(gen_secret)"
  done
  echo "FLEET_MCP_TOKEN=$(gen_secret)"
  echo "VERIFIER_TOKEN=$(gen_secret)"
  # The verifier proxies dependency installs under its own identity
  # (Stage 1c); it has no OpenCode server password.
  echo "PROXY_PW_VERIFIER=$(gen_secret)"
  echo "AGENCY_ADMIN_PASSWORD=$(gen_secret)"
} >"$ENVFILE"
chmod 600 "$ENVFILE"

{
  echo "# Generated by scripts/init-env.sh. Place the provider key here; never commit."
  echo "OPENCODE_API_KEY="
} >"$PROVIDERFILE"
chmod 600 "$PROVIDERFILE"

echo "init-env: wrote $ENVFILE and $PROVIDERFILE (0600). Set AGENCY_MODEL in .env and OPENCODE_API_KEY in .env.provider."
