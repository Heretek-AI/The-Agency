#!/usr/bin/env bash
# init-env for The Agency (Stage 1b, Step 7; allowlist in Stage 1d).
# From the salvaged studio init: creates .env (host uid/gid, gateway port,
# a random value for every PW_<NAME>, PROXY_PW_<NAME>, and token) and a
# placeholder .env.provider, both mode 0600, never overwriting an existing
# file. Never prints a secret: values are generated silently.
# Stage 1d addition: seeds state/registry/allowlist.yaml (admin, approver,
# viewer with argon2-hashed passwords) and the operator copy
# secrets/allowlist.env with the plaintext passwords, both mode 0600 and
# never overwritten.
set -u

ROOT="$(git rev-parse --show-toplevel)"
ENVFILE="$ROOT/.env"
PROVIDERFILE="$ROOT/.env.provider"
ALLOWLIST="$ROOT/state/registry/allowlist.yaml"
OPERATOR="$ROOT/secrets/allowlist.env"

if [ -f "$ENVFILE" ]; then
  echo "init-env: $ENVFILE exists; refusing to overwrite (delete it to re-init)" >&2
  exit 1
fi
if [ -f "$PROVIDERFILE" ]; then
  echo "init-env: $PROVIDERFILE exists; refusing to overwrite (delete it to re-init)" >&2
  exit 1
fi
if [ -f "$ALLOWLIST" ]; then
  echo "init-env: $ALLOWLIST exists; refusing to overwrite (delete it to re-init)" >&2
  exit 1
fi
if [ -f "$OPERATOR" ]; then
  echo "init-env: $OPERATOR exists; refusing to overwrite (delete it to re-init)" >&2
  exit 1
fi

command -v python3 >/dev/null 2>&1 || {
  echo "init-env: missing required command python3" >&2
  exit 1
}
command -v bun >/dev/null 2>&1 || {
  echo "init-env: missing required command bun (needed to hash allowlist passwords)" >&2
  exit 1
}

gen_secret() {
  python3 -c "import secrets; print(secrets.token_urlsafe(24))" || {
    echo "init-env: secret generation failed" >&2
    exit 1
  }
}

OPENCODE_VERSION="$(grep '^OPENCODE_VERSION=' "$ROOT/versions.env" | cut -d= -f2)"
BUN_VERSION="$(grep '^BUN_VERSION=' "$ROOT/versions.env" | cut -d= -f2)"
if [ -z "$OPENCODE_VERSION" ] || [ -z "$BUN_VERSION" ]; then
  echo "init-env: versions.env lacks OPENCODE_VERSION or BUN_VERSION" >&2
  exit 1
fi

{
  echo "# Generated by scripts/init-env.sh. Do not commit."
  echo "COMPOSE_PROJECT_NAME=agency"
  echo "AGENCY_MODEL="
  echo "AGENT_UID=$(id -u)"
  echo "AGENT_GID=$(id -g)"
  echo "AGENCY_HTTP_PORT=8081"
  echo "OPENCODE_VERSION=$OPENCODE_VERSION"
  echo "BUN_VERSION=$BUN_VERSION"
  for expert in director scout architect product frontend backend dba platform security qa reviewer docs; do
    upper=$(printf '%s' "$expert" | tr 'a-z-' 'A-Z_')
    echo "PW_$upper=$(gen_secret)"
    echo "PROXY_PW_$upper=$(gen_secret)"
  done
  echo "FLEET_MCP_TOKEN=$(gen_secret)"
  echo "VERIFIER_TOKEN=$(gen_secret)"
  # The verifier proxies dependency installs under its own identity
  # (Stage 1c); it has no OpenCode server password.
  echo "PROXY_PW_VERIFIER=$(gen_secret)"
  echo "AGENCY_ADMIN_PASSWORD=$(gen_secret)"
} >"$ENVFILE"
chmod 600 "$ENVFILE"

{
  echo "# Generated by scripts/init-env.sh. Place the provider key here; never commit."
  echo "OPENCODE_API_KEY="
} >"$PROVIDERFILE"
chmod 600 "$PROVIDERFILE"

ADMIN_PW="$(gen_secret)" || exit 1
APPROVER_PW="$(gen_secret)" || exit 1
VIEWER_PW="$(gen_secret)" || exit 1
ADMIN_HASH="$(bun -e 'console.log(await Bun.password.hash(process.argv[2], { algorithm: "argon2id" }))' "$ADMIN_PW")" || {
  echo "init-env: hashing the admin password failed" >&2
  exit 1
}
APPROVER_HASH="$(bun -e 'console.log(await Bun.password.hash(process.argv[2], { algorithm: "argon2id" }))' "$APPROVER_PW")" || {
  echo "init-env: hashing the approver password failed" >&2
  exit 1
}
VIEWER_HASH="$(bun -e 'console.log(await Bun.password.hash(process.argv[2], { algorithm: "argon2id" }))' "$VIEWER_PW")" || {
  echo "init-env: hashing the viewer password failed" >&2
  exit 1
}
mkdir -p "$ROOT/state/registry" "$ROOT/secrets"
{
  echo "# Generated by scripts/init-env.sh. Do not commit."
  echo "version: 1"
  echo "users:"
  echo "  - username: admin"
  echo "    role: admin"
  echo "    passwordHash: '$ADMIN_HASH'"
  echo "  - username: approver"
  echo "    role: approver"
  echo "    passwordHash: '$APPROVER_HASH'"
  echo "  - username: viewer"
  echo "    role: viewer"
  echo "    passwordHash: '$VIEWER_HASH'"
} >"$ALLOWLIST"
chmod 600 "$ALLOWLIST"
{
  echo "# Generated by scripts/init-env.sh. Operator copy of dashboard passwords; never commit."
  echo "AGENCY_ADMIN_PASSWORD=$ADMIN_PW"
  echo "AGENCY_APPROVER_PASSWORD=$APPROVER_PW"
  echo "AGENCY_VIEWER_PASSWORD=$VIEWER_PW"
} >"$OPERATOR"
chmod 600 "$OPERATOR"

echo "init-env: wrote $ENVFILE, $PROVIDERFILE, $ALLOWLIST, and $OPERATOR (0600). Set AGENCY_MODEL in .env and OPENCODE_API_KEY in .env.provider."
